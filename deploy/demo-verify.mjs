import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { pathToFileURL, fileURLToPath } from 'node:url';

const {chromium}=await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const secret=JSON.parse(await readFile(new URL('./secrets/demo-accounts.json',import.meta.url),'utf8'));
const origin='http://localhost:4001', evidence=new URL('../docs/qa/demo/',import.meta.url);
await mkdir(evidence,{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH}:{})});
const checks=[];
try {
  const context=await browser.newContext({viewport:{width:1365,height:950}}), page=await context.newPage();
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(origin);
  await page.getByRole('heading',{name:'Khám phá bộ sưu tập',exact:true}).waitFor();
  assert.equal(await page.getByRole('article').count(),8);
  await page.locator('img').evaluateAll(images=>Promise.all(images.map(image=>image.decode())));
  await page.screenshot({path:fileURLToPath(new URL('home-desktop.png',evidence)),fullPage:true});
  checks.push('8 visible demo products and all local images decode');
  await page.goto(origin+'/product/demo-iphone-1');
  await page.getByRole('heading',{name:'iPhone 16 · Demo',exact:true}).waitFor();
  await page.getByRole('button',{name:'Trắng',exact:true}).click();
  await page.getByText('Cấu hình chưa khả dụng.',{exact:false}).waitFor();
  checks.push('Out-of-stock color cannot be purchased');
  await page.goto(origin+'/login');
  await page.getByRole('button',{name:'Quản trị viên',exact:true}).click();
  await page.getByRole('heading',{name:'Đăng nhập quản trị',exact:true}).waitFor();
  await page.locator('input[name=email]').fill(secret.ownerEmail);
  await page.locator('input[name=password]').fill(secret.ownerPassword);
  await page.getByRole('button',{name:'Đăng nhập',exact:true}).click();
  await page.getByText(secret.ownerEmail,{exact:true}).waitFor();
  const ordersResponse=await context.request.get(origin+'/api/v1/admin/orders');assert.equal(ordersResponse.status(),200);
  const orders=await ordersResponse.json();assert.equal(orders.total,6);
  assert.deepEqual(orders.items.map(x=>x.status).sort(),['PENDING','PROCESSING','SHIPPED','DELIVERED','COMPLETED','CANCELLED'].sort());
  await page.goto(origin+'/admin/reports');
  await page.getByText('25.000.000 ₫',{exact:true}).first().waitFor();
  await page.screenshot({path:fileURLToPath(new URL('revenue-desktop.png',evidence)),fullPage:true});
  const completed=orders.items.find(order=>order.status==='COMPLETED');
  assert.equal(completed.paymentStatus,'PAID');
  checks.push('Owner UI login, six order states and 25 million VND completed/paid revenue');
  await context.request.post(origin+'/api/v1/admin/auth/logout',{headers:{Origin:origin,'X-Aura-Request':'1'}});
  const editor=await browser.newContext();
  const login=await editor.request.post(origin+'/api/v1/admin/auth/login',{headers:{Origin:origin,'X-Aura-Request':'1'},data:{email:secret.editorEmail,password:secret.editorPassword}});assert.equal(login.status(),200);
  assert.equal((await editor.request.get(origin+'/api/v1/admin/users')).status(),403);
  await editor.request.post(origin+'/api/v1/admin/auth/logout',{headers:{Origin:origin,'X-Aura-Request':'1'}});await editor.close();
  checks.push('Editor cannot manage admin accounts');
  const customer=await context.request.post(origin+'/api/v1/auth/login',{headers:{Origin:origin,'X-Aura-Request':'1'},data:{email:secret.customerEmail,password:secret.customerPassword}});assert.equal(customer.status(),200);
  const mine=await context.request.get(origin+'/api/v1/account/orders');assert.equal(mine.status(),200);assert.equal((await mine.json()).total,6);
  await context.request.post(origin+'/api/v1/auth/logout',{headers:{Origin:origin,'X-Aura-Request':'1'}});
  checks.push('Demo customer sees six own orders');
  await page.setViewportSize({width:390,height:844});await page.goto(origin);
  await page.getByRole('heading',{name:'Khám phá bộ sưu tập',exact:true}).waitFor();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:fileURLToPath(new URL('home-mobile.png',evidence)),fullPage:true});
  assert.deepEqual(errors,[]);checks.push('Mobile storefront fits and no browser page errors');
  await writeFile(new URL('results.json',evidence),JSON.stringify({at:new Date().toISOString(),origin,checks},null,2));
  console.log(JSON.stringify({passed:checks.length,checks}));
} finally {await browser.close();}
